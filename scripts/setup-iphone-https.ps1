<#
.SYNOPSIS
  Detects Windows LAN IPv4, prepares local HTTPS certificates & Caddyfile for iPhone 13 Safari.
.NOTES
  Never copies CA private keys to the iPhone. Only public rootCA.pem should be installed on iOS.
#>
param(
  [int]$HttpsPort = 443,
  [int]$WebPort = 3000,
  [int]$PhoneWebPort = 3001,
  [int]$ApiPort = 8000
)

$ErrorActionPreference = "Stop"

# 1. Detect active Wi-Fi / Ethernet IPv4 address (skip loopback, APIPA, and virtual adapters)
$candidates = Get-NetIPAddress -AddressFamily IPv4 -ErrorAction SilentlyContinue |
  Where-Object {
    $_.IPAddress -notlike "127.*" -and
    $_.IPAddress -notlike "169.254.*" -and
    $_.InterfaceAlias -notmatch "vEthernet|Loopback|WSL|Docker|VMware|VirtualBox"
  } |
  Sort-Object InterfaceMetric

if (-not $candidates -or $candidates.Count -eq 0) {
  Write-Error "No active LAN IPv4 address detected. Connect this Windows machine to Wi-Fi and retry."
  exit 1
}

$lanIp = ($candidates | Select-Object -First 1).IPAddress
$iface = ($candidates | Select-Object -First 1).InterfaceAlias
Write-Host "Detected Windows LAN IPv4: $lanIp (Interface: $iface)" -ForegroundColor Green

# 2. Validate local ports
foreach ($p in @($WebPort, $PhoneWebPort, $ApiPort)) {
  $listening = Get-NetTCPConnection -LocalPort $p -State Listen -ErrorAction SilentlyContinue
  if ($listening) {
    Write-Host "Port $p is currently LISTENING (ready)." -ForegroundColor Cyan
  } else {
    Write-Host "Port $p is not listening yet (start the service before testing)." -ForegroundColor Yellow
  }
}

# 3. Generate local TLS cert via mkcert if available
$certDir = Join-Path $PSScriptRoot "..\certs"
New-Item -ItemType Directory -Force -Path $certDir | Out-Null
$certFile = Join-Path $certDir "agentvoice-lan.pem"
$keyFile = Join-Path $certDir "agentvoice-lan-key.pem"

$mkcert = Get-Command mkcert -ErrorAction SilentlyContinue
if ($mkcert) {
  Write-Host "Found mkcert: generating trusted LAN certificate for $lanIp..." -ForegroundColor Green
  & mkcert -install
  & mkcert -cert-file $certFile -key-file $keyFile $lanIp localhost 127.0.0.1
  $caroot = & mkcert -CAROOT
  Write-Host "Public Root CA (safe to AirDrop/transfer to iPhone; NEVER share rootCA-key.pem):" -ForegroundColor Yellow
  Write-Host "  $caroot\rootCA.pem"
} else {
  Write-Host "mkcert not found. Install via 'winget install FiloSottile.mkcert' for trusted iOS Safari HTTPS." -ForegroundColor Yellow
  Write-Host "Generating Caddyfile template using $lanIp..."
}

# 4. Write Caddyfile.iphone
$caddyOut = Join-Path $PSScriptRoot "..\docker\caddy\Caddyfile.iphone"
New-Item -ItemType Directory -Force -Path (Split-Path $caddyOut) | Out-Null
$caddyContent = @"
# Auto-generated by scripts/setup-iphone-https.ps1 for LAN IP: $lanIp
https://${lanIp}:${HttpsPort} {
    tls $($certFile -replace '\\','/') $($keyFile -replace '\\','/')

    handle /api/* {
        reverse_proxy 127.0.0.1:${ApiPort}
    }

    handle {
        reverse_proxy 127.0.0.1:${WebPort}
    }
}

# Dedicated HTTPS origin for agentvoice-phone-web (iPhone Safari PWA)
https://${lanIp}:8443 {
    tls $($certFile -replace '\\','/') $($keyFile -replace '\\','/')

    handle /api/* {
        reverse_proxy 127.0.0.1:${ApiPort}
    }

    handle {
        reverse_proxy 127.0.0.1:${PhoneWebPort}
    }
}
"@
Set-Content -Path $caddyOut -Value $caddyContent -Encoding UTF8

Write-Host ""
Write-Host "=== iPhone 13 Safari Setup Summary ===" -ForegroundColor Green
Write-Host "1. Open Windows Firewall (Admin PowerShell) for LAN HTTPS only (do NOT expose 3000/3001/8000 publicly):"
Write-Host "   New-NetFirewallRule -DisplayName 'agentVoice HTTPS LAN' -Direction Inbound -LocalPort $HttpsPort,8443 -Protocol TCP -Action Allow -Profile Private"
Write-Host "2. Install rootCA.pem on iPhone 13 (iOS 26):"
Write-Host "   - Transfer rootCA.pem (NOT rootCA-key.pem) to iPhone -> Settings > General > VPN & Device Management > Install Profile"
Write-Host "   - Settings > General > About > Certificate Trust Settings > Enable Full Trust for mkcert CA"
Write-Host "3. Start Caddy reverse proxy:"
Write-Host "   caddy run --config docker\caddy\Caddyfile.iphone"
Write-Host "4. Open in iPhone Safari:"
Write-Host "   https://${lanIp}:8443" -ForegroundColor Cyan
